#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CATALOG="${ROOT}/config/avcd-openrouter-models.json"
ENV_FILE="${PREPARE_DEV_UI_ENV_FILE:-${ROOT}/ui/desktop/.env}"
SERVER_PORT="${SERVER_PORT:-3000}"
GATEWAY_PORT="${GATEWAY_PORT:-3100}"
SECRET="${GOOSE_SERVER__SECRET_KEY:-avcd-agent-local-development-key}"

# Zitadel desktop login: first existing file wins.
if [[ -z "${ZITADEL_OAUTH_ENV:-}" ]]; then
  for candidate in \
    "${ROOT}/config/avcd-agent-oauth.env" \
    "${ROOT}/../avcd-zitadel/config/avcd-agent-oauth.env"; do
    if [[ -f "${candidate}" ]]; then
      ZITADEL_OAUTH_ENV="${candidate}"
      break
    fi
  done
fi

AUTH_MODE=false
if [[ -n "${ZITADEL_OAUTH_ENV:-}" && -f "${ZITADEL_OAUTH_ENV}" ]]; then
  AUTH_MODE=true
fi

if [[ "${DEV_UI_LEGACY:-}" == "1" || "${FORCE_LEGACY_DEV_UI:-}" == "1" ]]; then
  AUTH_MODE=false
fi

python3 - "${CATALOG}" "${ENV_FILE}" "${SERVER_PORT}" "${GATEWAY_PORT}" "${SECRET}" "${AUTH_MODE}" "${ZITADEL_OAUTH_ENV:-}" <<'PY'
import json
import sys
from pathlib import Path

catalog_path = Path(sys.argv[1])
env_path = Path(sys.argv[2])
legacy_port = sys.argv[3]
gateway_port = sys.argv[4]
secret = sys.argv[5]
auth_mode = sys.argv[6] == "true"
oauth_env = sys.argv[7]

catalog = json.loads(catalog_path.read_text())
provider = catalog["provider"]
default_model = catalog["defaultModel"]
models = [
    {
        "name": model["name"],
        "provider": provider,
        "alias": model["alias"],
        "subtext": model["subtext"],
    }
    for model in catalog["models"]
]
models_json = json.dumps(models, separators=(",", ":"), ensure_ascii=True)

if "'" in models_json:
    raise SystemExit("provider catalog cannot be encoded safely in dotenv")

lines: list[str] = []

if auth_mode:
    oauth_path = Path(oauth_env)
    if not oauth_path.is_file():
        raise SystemExit(f"Zitadel oauth env not found: {oauth_env}")

    lines.append("# Generated by make dev-ui — Zitadel login via avcd-agent-gateway.")
    lines.append("AVCD_AUTH_MODE=zitadel")
    for raw in oauth_path.read_text().splitlines():
        stripped = raw.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _ = stripped.split("=", 1)
        # Gateway-only settings must not leak into the Electron process.
        if key == "JWT_REQUIRED":
            continue
        lines.append(stripped)
    lines.extend(
        [
            "GOOSE_EXTERNAL_BACKEND=true",
            f"GOOSE_EXTERNAL_BACKEND_URL=http://127.0.0.1:{gateway_port}",
            "GOOSE_WORKING_DIR=/workspace",
            "GOOSE_MODE=smart_approve",
            f"GOOSE_DEFAULT_PROVIDER={provider}",
            f"GOOSE_DEFAULT_MODEL={default_model}",
            f"GOOSE_PREDEFINED_MODELS='{models_json}'",
            "",
        ]
    )
else:
    if "'" in secret or "\n" in secret:
        raise SystemExit("server secret cannot be encoded safely in dotenv")

    lines.extend(
        [
            "# Generated by make dev-ui — connects the desktop app to the Docker ACP backend.",
            "# For Zitadel login create config/avcd-agent-oauth.env, then rerun make dev-ui.",
            "GOOSE_EXTERNAL_BACKEND=true",
            f"GOOSE_EXTERNAL_BACKEND_URL=http://127.0.0.1:{legacy_port}",
            f"GOOSE_SERVER__SECRET_KEY='{secret}'",
            # Container path (compose mounts ./workspace → /workspace). Host $HOME is not mounted.
            "GOOSE_WORKING_DIR=/workspace",
            # Consumer default: ask before sensitive tool calls (matches GooseMode::default).
            "GOOSE_MODE=smart_approve",
            # Pin OAuth callback port so hosted Google Workspace can allowlist Goose.
            "GOOSE_OAUTH_CALLBACK_PORT=18787",
            f"GOOSE_DEFAULT_PROVIDER={provider}",
            f"GOOSE_DEFAULT_MODEL={default_model}",
            f"GOOSE_PREDEFINED_MODELS='{models_json}'",
            "",
        ]
    )

env_path.parent.mkdir(parents=True, exist_ok=True)
env_path.write_text("\n".join(lines))
PY

if [[ "${AUTH_MODE}" == "true" ]]; then
  echo "Wrote ${ENV_FILE} for Zitadel login (gateway :${GATEWAY_PORT}, oauth: ${ZITADEL_OAUTH_ENV})"
else
  echo "Wrote ${ENV_FILE} with AVCD OpenRouter defaults (Docker backend, no login gate)"
  echo "Tip: create config/avcd-agent-oauth.env to enable the login screen in make dev-ui"
fi
